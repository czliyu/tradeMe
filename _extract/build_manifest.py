# ---------------- copy + write manifest ----------------
missing = []
for dst, src, book, ch, lab, title, desc in M:
    out = os.path.join(IMG, dst)
    if not os.path.exists(src):
        missing.append(src); continue
    shutil.copyfile(src, out)

lines = ["# 插图清单（图号→文件，第一列就是要写进 md 的相对路径）\n"]
rows = [(b,c,f"images/{dst}",lab,title,desc) for dst,src,b,c,lab,title,desc in M]
rows += [(b,c,path,lab,title,desc) for b,c,path,lab,title,desc in EXIST]
rows.sort(key=lambda r: (r[0], r[1], r[2]))
last = None
for b,c,path,lab,title,desc in rows:
    key = (b, c)
    if key != last:
        last = key
        lines.append(f"\n## 书{b} · 第{c}章\n")
        lines.append("| 文件 | 图号 | 图题 | 内容 |\n|---|---|---|---|\n")
    lines.append(f"| {path} | {lab} | {title} | {desc} |\n")
with open(os.path.join(BASE, "_extract/manifest.md"), "w") as f:
    f.writelines(lines)

